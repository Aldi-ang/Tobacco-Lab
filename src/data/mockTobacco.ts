function createCelloSerial(params: {
  id: string;
  seri: string;
  idx: number;
  bruto: number;
  tara: number;
  realPkgMassKg?: number;
  grade: 'E' | 'D' | 'D+';
  costPerKg: number;
  settledPricePerKg: number;
  status?: 'PENDING' | 'ACCEPTED_CAIR' | 'REJECTED_STOCK';
  rollId?: string;
  rollNumber?: string;
  previousRollNumber?: string;
  previousFactory?: string;
  rejectionNotes?: string;
}): FinishedTobaccoSerial {
  const realPkgMassKg = params.realPkgMassKg ?? params.tara;
  const nettoBillable = params.bruto - params.tara;
  const realTobaccoNetKg = Math.max(0, params.bruto - realPkgMassKg);
  const factoryWeightProfitKg = Number((nettoBillable - realTobaccoNetKg).toFixed(2));
  const factoryWeightProfitRp = Math.round(factoryWeightProfitKg * params.settledPricePerKg);
  const packagingCostRp = 35000;
  const pressCostRp = 15000;
  const overhead = packagingCostRp + pressCostRp;
  const materialCost = Math.round(realTobaccoNetKg * params.costPerKg - overhead);
  const totalProdCost = Math.round(realTobaccoNetKg * params.costPerKg);
  const revenue = Math.round(nettoBillable * params.settledPricePerKg);
  const profit = revenue - totalProdCost;

  const baseIngredients =
    params.grade === 'E'
      ? CELLO_MUNTILAN_INGREDIENTS
      : params.grade === 'D+'
      ? GRADE_D_PLUS_INGREDIENTS
      : GRADE_D_INGREDIENTS;

  return {
    id: params.id,
    serialNumber: params.seri,
    mixtureBatchId: 'MIX-CELLO-2026',
    packageIndex: params.idx,
    totalPackagesInMixture: 6,
    recipeName: `CELLO MUNTILAN - Seri ${params.seri}`,
    targetFactoryId: 'fac-cello-muntilan',
    targetFactory: 'CELLO MUNTILAN',
    createdAt: '2026-11-03',
    ingredients: baseIngredients.map((ing) => {
      const shareRatio = (ing.percentageInBlend || 50) / 100;
      const portionKg = Number((realTobaccoNetKg * shareRatio).toFixed(1));
      return {
        ...ing,
        usedNetKg: portionKg,
        subtotalCost: Math.round(portionKg * ing.realCostPerNetKg),
      };
    }),
    totalBlendNetKg: realTobaccoNetKg,
    weightedPower: params.grade === 'E' ? 4.3 : params.grade === 'D+' ? 3.8 : 3.5,
    weightedImpact: params.grade === 'E' ? 4.1 : params.grade === 'D+' ? 3.7 : 3.6,
    weightedBitter: params.grade === 'E' ? 2.4 : params.grade === 'D+' ? 2.4 : 2.8,
    weightedBurn: params.grade === 'E' ? 4.7 : params.grade === 'D+' ? 4.6 : 4.1,
    weightedSugar: params.grade === 'E' ? 4.1 : params.grade === 'D+' ? 4.2 : 3.8,
    weightedAroma: params.grade === 'E' ? 4.6 : params.grade === 'D+' ? 4.4 : 4.1,
    compositeColorGrade: params.grade,
    totalMaterialCost: materialCost,
    additionalCosts: [
      { id: `pkg-${params.seri}`, name: 'Harga Kemasan KRJ MUNTILAN', amount: packagingCostRp },
      { id: `prs-${params.seri}`, name: 'Ongkos Packaging / Press', amount: pressCostRp },
    ],
    totalOverheadCost: overhead,
    totalProductionCost: totalProdCost,
    hppPerNetKg: params.costPerKg,
    effectiveHppAfterTaraPerKg:
      nettoBillable > 0 ? Math.round((totalProdCost / nettoBillable) * 100) / 100 : params.costPerKg,
    packaging: {
      packagingId: 'pkg-krj-muntilan',
      packagingType: 'KRJ MUNTILAN',
      packagingMassKg: realPkgMassKg,
      packageCount: 1,
      netTobaccoWeightKg: realTobaccoNetKg,
      grossWeightPerPackage: params.bruto,
      packagingCostRp,
      pressCostRp,
      factoryTaraFormula: {
        rawFormula: `${params.tara} kg`,
        percent: 0,
        flatKg: params.tara,
        sampleKg: 0,
        pricingBasis: 'NET_WEIGHT',
        packagingType: 'KRJ MUNTILAN',
        packagingMassKg: realPkgMassKg,
      },
    },
    factoryDeductionKg: params.tara,
    factoryNetBillableKg: nettoBillable,
    factoryWeightProfitKg,
    factoryWeightProfitRp,
    factoryTargetPricePerKg: params.settledPricePerKg,
    projectedRevenue: revenue,
    projectedProfit: profit,
    profitMarginPercent: revenue > 0 ? Number(((profit / revenue) * 100).toFixed(2)) : 0,
    factoryStatus: params.status || 'ACCEPTED_CAIR',
    previousRollNumber: params.previousRollNumber,
    previousFactory: params.previousFactory,
    rejectionNotes: params.rejectionNotes,
    rollId: params.rollId || 'gul-2026-001',
    rollNumber: params.rollNumber || 'GUL-2026-001',
    rollRackNumber: 'Lemari Sampel Cello Muntilan - Rak 01',
    notes: `Kemasan KRJ MUNTILAN Seri ${params.seri} (Bruto ${params.bruto}kg, Wadah Riil ${realPkgMassKg}kg, Tara Pabrik ${params.tara}kg, Netto Tagih ${nettoBillable}kg).`,
  };
}

